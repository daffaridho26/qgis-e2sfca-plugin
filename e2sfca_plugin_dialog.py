    # ==================================================================
    # LAYER & FIELD
    # ==================================================================
    @staticmethod
    def _layer_matches(layer, kind):
        if not isinstance(layer, QgsVectorLayer) or not layer.isValid():
            return False
        geom = layer.geometryType()
        if kind == "polypoint":
            return geom in (QgsWkbTypes.PointGeometry, QgsWkbTypes.PolygonGeometry)
        if kind == "line":
            return geom == QgsWkbTypes.LineGeometry
        return False

    def _fill_layer_combo(self, combo, kind, select_id=None):
        """Fill the combo with layers of the given geometry type, keeping the
        current selection."""
        keep_id = select_id or combo.currentData()
        combo.blockSignals(True)
        combo.clear()
        for layer in QgsProject.instance().mapLayers().values():
            if self._layer_matches(layer, kind):
                combo.addItem(layer.name(), layer.id())
        if keep_id:
            idx = combo.findData(keep_id)
            if idx >= 0:
                combo.setCurrentIndex(idx)
        combo.blockSignals(False)

    def populate_layers(self):
        """comboBox & comboBox_3: point/polygon; comboBox_5: line."""
        self._fill_layer_combo(self.comboBox, "polypoint")
        self._fill_layer_combo(self.comboBox_3, "polypoint")
        self._fill_layer_combo(self.comboBox_5, "line")
        self.populate_facility_fields()
        self.populate_pop_fields()
        self.populate_road_fields()

    def showEvent(self, event):
        # Refresh the layer lists every time the dialog is opened
        if not self._is_running:
            self.populate_layers()
        super().showEvent(event)

    @staticmethod
    def _layer_from_combo(combo):
        layer_id = combo.currentData()
        return QgsProject.instance().mapLayer(layer_id) if layer_id else None

    @staticmethod
    def _fill_field_combo(combo, layer, numeric_only=True, optional=False):
        current = combo.currentText()
        combo.blockSignals(True)
        combo.clear()
        if optional:
            combo.addItem(NO_FIELD)
        if layer:
            for field in layer.fields():
                if not numeric_only or field.isNumeric():
                    combo.addItem(field.name())
        idx = combo.findText(current)
        if idx >= 0:
            combo.setCurrentIndex(idx)
        combo.blockSignals(False)

    def populate_facility_fields(self):
        """comboBox_2: capacity fields of the layer selected in comboBox."""
        self._fill_field_combo(self.comboBox_2, self._layer_from_combo(self.comboBox))

    def populate_pop_fields(self):
        """comboBox_4: population fields of the layer selected in comboBox_3."""
        self._fill_field_combo(self.comboBox_4, self._layer_from_combo(self.comboBox_3))

    def populate_road_fields(self):
        """comboBox_9 (direction, any field type) & comboBox_7 (speed, numeric)."""
        road = self._layer_from_combo(self.comboBox_5)
        self._fill_field_combo(self.comboBox_9, road, numeric_only=False, optional=True)
        self._fill_field_combo(self.comboBox_7, road, numeric_only=True, optional=True)
        self.toggle_direction_widgets()


    # ==================================================================
    # BROWSE FILE
    # ==================================================================
    def browse_layer(self, combo, kind):
        path, _ = QtWidgets.QFileDialog.getOpenFileName(
            self, "Select Vector Data", "",
            "Vector data (*.shp *.gpkg);;ESRI Shapefile (*.shp);;GeoPackage (*.gpkg)"
        )
        if not path:
            return

        uri = path
        name = os.path.splitext(os.path.basename(path))[0]

        # A GeoPackage may contain several layers -> let the user choose one
        if path.lower().endswith(".gpkg"):
            try:
                from osgeo import ogr
                ds = ogr.Open(path)
                names = [ds.GetLayerByIndex(i).GetName()
                         for i in range(ds.GetLayerCount())] if ds else []
                ds = None
            except Exception:
                names = []
            if len(names) > 1:
                chosen, ok = QtWidgets.QInputDialog.getItem(
                    self, "Select Layer", "Layers in the GeoPackage:",
                    names, 0, False)
                if not ok:
                    return
                name = chosen
                uri = f"{path}|layername={chosen}"
            elif len(names) == 1:
                name = names[0]
                uri = f"{path}|layername={names[0]}"

        layer = QgsVectorLayer(uri, name, "ogr")
        if not layer.isValid():
            QtWidgets.QMessageBox.warning(self, "Warning",
                                          "The file cannot be read as a vector layer.")
            return
        if not self._layer_matches(layer, kind):
            msg = ("The layer must be of Point or Polygon type."
                   if kind == "polypoint" else "The layer must be of Line type.")
            QtWidgets.QMessageBox.warning(self, "Invalid Geometry Type", msg)
            return

        QgsProject.instance().addMapLayer(layer)
        # Refresh all combos, then select the new layer in the calling combo
        self._fill_layer_combo(self.comboBox, "polypoint")
        self._fill_layer_combo(self.comboBox_3, "polypoint")
        self._fill_layer_combo(self.comboBox_5, "line")
        combo.setCurrentIndex(combo.findData(layer.id()))
        self.populate_facility_fields()
        self.populate_pop_fields()
        self.populate_road_fields()


    # ==================================================================
    # ENABLE / DISABLE WIDGETS
    # ==================================================================
    def toggle_direction_widgets(self):
        """lineEdit 1-3 & label_13-15 are enabled only when a field is set in comboBox_9."""
        active = bool(self.comboBox_9.currentText())
        for w in (self.label_13, self.label_14, self.label_15,
                  self.lineEdit, self.lineEdit_2, self.lineEdit_3):
            w.setEnabled(active)

    def update_direction_hints(self):
        """Show the unique values of the selected direction field as a
        tooltip and autocomplete list on lineEdit 1-3."""
        road = self._layer_from_combo(self.comboBox_5)
        field = self.comboBox_9.currentText()
        values = []
        if road and field:
            idx = road.fields().indexFromName(field)
            if idx >= 0:
                values = sorted(str(v) for v in road.uniqueValues(idx, 50)
                                if v is not None and str(v) != "NULL")

        tip = (f"Values in '{field}': " + ", ".join(values)) if values else ""
        completer = QtWidgets.QCompleter(values, self)
        completer.setCaseSensitivity(Qt.CaseInsensitive)
        for le in (self.lineEdit, self.lineEdit_2, self.lineEdit_3):
            le.setToolTip(tip)
            le.setCompleter(completer)

    def toggle_decay_widgets(self):
        """label_16 & doubleSpinBox_3 are enabled only for the Exponential Function."""
        is_exp = self.comboBox_8.currentText() == DECAY_EXPONENTIAL
        self.label_16.setEnabled(is_exp)
        self.doubleSpinBox_3.setEnabled(is_exp)

    def toggle_impedance_widgets(self):
        """label_7, comboBox_7, label_8, doubleSpinBox are enabled only for Travel Time."""
        is_time = self.comboBox_6.currentText() == IMPEDANCE_TIME
        for w in (self.label_7, self.comboBox_7, self.label_8, self.doubleSpinBox):
            w.setEnabled(is_time)

        # The cut-off unit follows the impedance type
        if is_time:
            self.doubleSpinBox_2.setSuffix(" min")
            if self.doubleSpinBox_2.value() > 300:
                self.doubleSpinBox_2.setValue(30.0)
        else:
            self.doubleSpinBox_2.setSuffix(" m")
            if self.doubleSpinBox_2.value() < 100:
                self.doubleSpinBox_2.setValue(5000.0)


    # ==================================================================
    # CANCEL
    # ==================================================================
    def cancel_or_close(self):
        if self._is_running and self.feedback:
            self.feedback.cancel()   # the pipeline stops, then the dialog closes
        else:
            self.reject()

    def closeEvent(self, event):
        if self._is_running and self.feedback:
            self.feedback.cancel()
        super().closeEvent(event)

    def _on_progress(self, value):
        """Forward pipeline progress to the progressBar and keep the UI responsive."""
        self.progressBar.setValue(int(value))
        QCoreApplication.processEvents()


    # ==================================================================
    # RUN (pushButton_2)
    # ==================================================================
    def collect_params(self):
        """Read all widgets -> E2SFCAParams. The only place where widgets are read."""
        return E2SFCAParams(
            facility_layer=self._layer_from_combo(self.comboBox),
            capacity_field=self.comboBox_2.currentText(),
            population_layer=self._layer_from_combo(self.comboBox_3),
            population_field=self.comboBox_4.currentText(),
            road_layer=self._layer_from_combo(self.comboBox_5),
            is_travel_time=self.comboBox_6.currentText() == IMPEDANCE_TIME,
            direction_field=self.comboBox_9.currentText(),
            forward_value=self.lineEdit.text().strip(),
            backward_value=self.lineEdit_2.text().strip(),
            both_value=self.lineEdit_3.text().strip(),
            speed_field=self.comboBox_7.currentText(),
            default_speed=self.doubleSpinBox.value(),
            decay_function=self.comboBox_8.currentText(),
            beta=self.doubleSpinBox_3.value(),
            cutoff=self.doubleSpinBox_2.value(),
            point_method=POINT_ON_SURFACE,
            output_path=self.mQgsFileWidget.filePath().strip(),
        )

    def run_analysis(self):
        params = self.collect_params()

        self.feedback = QgsFeedback()
        self.feedback.progressChanged.connect(self._on_progress)
        self._is_running = True
        self.pushButton_2.setEnabled(False)
        self.progressBar.setValue(0)

        result = None
        try:
            result = run_e2sfca(params, self.feedback)
        except InputError as e:
            QtWidgets.QMessageBox.warning(self, "Invalid Input Data", str(e))
        except Exception as e:
            QtWidgets.QMessageBox.critical(self, "Error", f"An error occurred:\n{e}")
        finally:
            self._is_running = False
            self.pushButton_2.setEnabled(True)

        canceled = self.feedback.isCanceled()
        self.feedback = None

        if canceled:
            self.progressBar.setValue(0)
            if self.iface:
                self.iface.messageBar().pushMessage(
                    "E2SFCA", "Process canceled.", level=Qgis.Warning, duration=4)
            self.reject()
            return

        if result is None:
            self.progressBar.setValue(0)
            return

        if self.checkBox.isChecked():
            layer = QgsVectorLayer(result.output_path, result.layer_name, "ogr")
            QgsProject.instance().addMapLayer(layer)

        self.progressBar.setValue(100)
        msg = ("Output saved as a temporary file:\n"
               f"{result.output_path}\nThis file will be deleted when QGIS is closed."
               if result.is_temporary else
               f"Output saved to:\n{result.output_path}")
        msg += "\nIndex attribute: 'SAI_E2SFCA'."
        if result.warnings:
            msg += "\n\nNotes:\n" + "\n".join(f"- {w}" for w in result.warnings)
        QtWidgets.QMessageBox.information(self, "Completed", msg)
 