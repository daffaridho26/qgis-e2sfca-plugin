    # ==================================================================
    # DESCRIPTION BOX
    # ==================================================================
    def load_help(self):
        """Load the description box content from e2sfca_help.html."""
        if os.path.exists(HELP_FILE):
            with open(HELP_FILE, encoding="utf-8") as fh:
                self.textBrowser.setHtml(fh.read())
        else:
            self.textBrowser.setPlainText(
                "Description file not found:\n" + HELP_FILE)

    def toggle_help(self, checked):
        """Show or hide the description panel. Only the window width is
        changed so the left panel keeps its size."""
        resize = self.isVisible() and not self.isMaximized()
        if checked:
            self.textBrowser.setVisible(True)
            if resize:
                self.resize(self.width() + self._help_width, self.height())
        else:
            if self.isVisible():
                self._help_width = (self.textBrowser.width()
                                    + self.horizontalLayout_4.spacing())
            self.textBrowser.setVisible(False)
            if resize:
                self.resize(self.width() - self._help_width, self.height())
        self.toolButton_4.setText("▶" if checked else "◀")


