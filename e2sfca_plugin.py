import os.path
from qgis.PyQt.QtCore import QCoreApplication
from qgis.PyQt.QtGui import QIcon
from qgis.PyQt.QtWidgets import QAction
from qgis.core import QgsProject

from .e2sfca_plugin_dialog import E2SFCAPluginDialog


class E2SFCAPlugin:

    def __init__(self, iface):
        self.iface = iface
        self.plugin_dir = os.path.dirname(__file__)
        self.actions = []
        self.menu = '&E2SFCA Plugin'
        self.dlg = None

    def initGui(self):
        """Add the plugin icon to the QGIS toolbar and Vector menu."""
        icon_path = os.path.join(self.plugin_dir, 'icon.png')
        self.action = QAction(
            QIcon(icon_path),
            'E2SFCA Accessibility Calculator',
            self.iface.mainWindow(),
        )
        self.action.triggered.connect(self.run)
        self.iface.addPluginToVectorMenu(self.menu, self.action)
        self.iface.addToolBarIcon(self.action)
        self.actions.append(self.action)

         # Keep the layer lists in sync while the (non-modal) dialog is open
        project = QgsProject.instance()
        project.layersAdded.connect(self._refresh_layers)
        project.layersRemoved.connect(self._refresh_layers)

    def unload(self):
        """Remove the plugin icon/menu and clean up the dialog."""
        project = QgsProject.instance()
        for signal in (project.layersAdded, project.layersRemoved):
            try:
                signal.disconnect(self._refresh_layers)
            except TypeError:
                pass

        for action in self.actions:
            self.iface.removePluginVectorMenu(self.menu, action)
            self.iface.removeToolBarIcon(action)
        self.actions = []

        if self.dlg is not None:
            if self.dlg._is_running and self.dlg.feedback:
                self.dlg.feedback.cancel()
            self.dlg.close()
            self.dlg.deleteLater()
            self.dlg = None

    def _refresh_layers(self, *args):
        """Refresh the dialog layer lists when layers are added/removed."""
        if self.dlg is not None and self.dlg.isVisible() and not self.dlg._is_running:
            self.dlg.populate_layers()

    def run(self):
        """Called when the plugin icon is clicked."""
        if self.dlg is None:
            self.dlg = E2SFCAPluginDialog(self.iface, self.iface.mainWindow())

        # Do not touch the combos while a calculation is running
        if not self.dlg._is_running:
            self.dlg.populate_layers()

        # Show the dialog without blocking the map canvas
        self.dlg.show()
        self.dlg.raise_()
        self.dlg.activateWindow()
        
